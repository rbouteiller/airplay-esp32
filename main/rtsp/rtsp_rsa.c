// Parsed as a PSA RSA key pair, usable for both operations below (set via
// psa_set_key_enrollment_algorithm(), since a PSA key policy otherwise
// allows only a single algorithm).
static mbedtls_svc_key_id_t s_rsa_key;
static bool s_pk_initialized = false;

// A private-key op is not reentrant against a concurrent op on the same key
// in every PSA driver, and client tasks overlap during a handover, so every
// use of s_rsa_key is serialised.
static SemaphoreHandle_t s_rsa_lock;
static StaticSemaphore_t s_rsa_lock_storage;
static portMUX_TYPE s_rsa_lock_mux = portMUX_INITIALIZER_UNLOCKED;

// Creating the lock has to be race-free too: a client task can reach a
// private-key op without rsa_init() having run first.
static SemaphoreHandle_t rsa_lock(void) {
  portENTER_CRITICAL(&s_rsa_lock_mux);
  if (s_rsa_lock == NULL) {
    s_rsa_lock = xSemaphoreCreateMutexStatic(&s_rsa_lock_storage);
  }
  portEXIT_CRITICAL(&s_rsa_lock_mux);
  return s_rsa_lock;
}

static int ensure_pk_initialized_locked(void) {
  if (s_pk_initialized) {
    return 0;
  }

  int64_t start_us = esp_timer_get_time();

  psa_status_t status = psa_crypto_init();
  if (status != PSA_SUCCESS) {
    ESP_LOGE(TAG, "psa_crypto_init failed: %d", (int)status);
    return -1;
  }

  psa_key_attributes_t attr = PSA_KEY_ATTRIBUTES_INIT;
  psa_set_key_type(&attr, PSA_KEY_TYPE_RSA_KEY_PAIR);
  psa_set_key_usage_flags(&attr,
                          PSA_KEY_USAGE_SIGN_HASH | PSA_KEY_USAGE_DECRYPT);
  // Primary alg: OAEP-SHA1 decrypt (rsa_decrypt_aes_key). Enrollment alg:
  // raw PKCS#1 v1.5 sign (rsa_apple_challenge_response) — a PSA key policy
  // only grants one algorithm unless a second is enrolled this way.
  psa_set_key_algorithm(&attr, PSA_ALG_RSA_OAEP(PSA_ALG_SHA_1));
  psa_set_key_enrollment_algorithm(&attr, PSA_ALG_RSA_PKCS1V15_SIGN_RAW);

  status = psa_import_key(&attr, airplay_rsa_private_key_der,
                          sizeof(airplay_rsa_private_key_der), &s_rsa_key);
  if (status != PSA_SUCCESS) {
    ESP_LOGE(TAG, "Failed to import RSA private key: %d", (int)status);
    return -1;
  }

  // The first private-key op also derives the blinding pair, which costs an
  // inv_mod and an exp_mod that later calls avoid by squaring the cached one.
  // Throw one signature away here so a sender never waits for it.
  uint8_t scratch[32] = {0};
  uint8_t warm[256];
  size_t warm_len = 0;
  psa_sign_hash(s_rsa_key, PSA_ALG_RSA_PKCS1V15_SIGN_RAW, scratch,
                sizeof(scratch), warm, sizeof(warm), &warm_len);

  s_pk_initialized = true;

  ESP_LOGI(TAG, "RSA key ready in %lld ms",
           (esp_timer_get_time() - start_us) / 1000);
  return 0;
}

int rsa_init(void) {
  SemaphoreHandle_t lock = rsa_lock();
  xSemaphoreTake(lock, portMAX_DELAY);
  int ret = ensure_pk_initialized_locked();
  xSemaphoreGive(lock);
  return ret;
}

// Simple base64 decode using libsodium
static int b64_decode(const char *b64, uint8_t *out, size_t out_size,
                      size_t *out_len) {
  // Apple base64 may lack padding — libsodium handles that with _IGNORE variant
  if (sodium_base642bin(out, out_size, b64, strlen(b64), "\r\n \t", out_len,
                        NULL, sodium_base64_VARIANT_ORIGINAL_NO_PADDING) != 0) {
    // Try with padding variant
    if (sodium_base642bin(out, out_size, b64, strlen(b64), "\r\n \t", out_len,
                          NULL, sodium_base64_VARIANT_ORIGINAL) != 0) {
      return -1;
    }
  }
  return 0;
}

// Simple base64 encode using libsodium, strip trailing '='
static int b64_encode(const uint8_t *data, size_t data_len, char *out,
                      size_t out_size) {
  char *result = sodium_bin2base64(out, out_size, data, data_len,
                                   sodium_base64_VARIANT_ORIGINAL_NO_PADDING);
  return result ? 0 : -1;
}

int rsa_apple_challenge_response(const char *challenge_b64, uint32_t ip_addr,
                                 const uint8_t mac[6], char *out_b64,
                                 size_t out_b64_size) {
  // Decode challenge
  uint8_t challenge[32];
  size_t challenge_len = 0;
  if (b64_decode(challenge_b64, challenge, sizeof(challenge), &challenge_len) !=
      0) {
    ESP_LOGE(TAG, "Failed to decode Apple-Challenge");
    return -1;
  }

  // Build response data: challenge + IP(4) + MAC(6), padded to 32 bytes
  uint8_t data[32];
  memset(data, 0, sizeof(data));
  size_t pos = 0;

  if (challenge_len > 22) {
    challenge_len = 22; // Max room for challenge if IP + MAC must fit
  }
  memcpy(data + pos, challenge, challenge_len);
  pos += challenge_len;

  memcpy(data + pos, &ip_addr, 4);
  pos += 4;

  memcpy(data + pos, mac, 6);
  // pos is now at most 32, rest is zero-padded

  // RSA PKCS1 v1.5 "private encrypt" — equivalent to OpenSSL's
  // RSA_private_encrypt(..., RSA_PKCS1_PADDING).
  // PSA_ALG_RSA_PKCS1V15_SIGN_RAW applies type-1 padding
  // (0x00 0x01 0xFF..0xFF 0x00 <data>) then the private key operation,
  // same as the legacy mbedtls_rsa_pkcs1_sign(..., MBEDTLS_MD_NONE, ...) this
  // replaced.
  SemaphoreHandle_t lock = rsa_lock();
  xSemaphoreTake(lock, portMAX_DELAY);

  if (ensure_pk_initialized_locked() != 0) {
    xSemaphoreGive(lock);
    return -1;
  }

  uint8_t rsa_out[256]; // 2048-bit key
  size_t rsa_len = 0;
  psa_status_t status =
      psa_sign_hash(s_rsa_key, PSA_ALG_RSA_PKCS1V15_SIGN_RAW, data,
                    sizeof(data), rsa_out, sizeof(rsa_out), &rsa_len);
  xSemaphoreGive(lock);

  if (status != PSA_SUCCESS) {
    ESP_LOGE(TAG, "RSA sign failed: %d", (int)status);
    return -1;
  }

  // Base64 encode result without padding
  if (b64_encode(rsa_out, rsa_len, out_b64, out_b64_size) != 0) {
    ESP_LOGE(TAG, "Failed to base64-encode RSA response");
    return -1;
  }

  return 0;
}

int rsa_decrypt_aes_key(const char *encrypted_b64, uint8_t *out_key,
                        size_t out_key_size, size_t *out_key_len) {
  // Decode the base64 RSA-encrypted key
  uint8_t encrypted[512];
  size_t encrypted_len = 0;
  if (b64_decode(encrypted_b64, encrypted, sizeof(encrypted), &encrypted_len) !=
      0) {
    ESP_LOGE(TAG, "Failed to decode RSA-encrypted AES key");
    return -1;
  }

  ESP_LOGI(TAG, "RSA-encrypted AES key: %zu bytes (expected 256)",
           encrypted_len);

  // RSA OAEP-SHA1 decrypt (RAOP uses OAEP padding for the AES key)
  SemaphoreHandle_t lock = rsa_lock();
  xSemaphoreTake(lock, portMAX_DELAY);

  if (ensure_pk_initialized_locked() != 0) {
    xSemaphoreGive(lock);
    return -1;
  }

  size_t olen = 0;
  psa_status_t status = psa_asymmetric_decrypt(
      s_rsa_key, PSA_ALG_RSA_OAEP(PSA_ALG_SHA_1), encrypted, encrypted_len,
      NULL, 0, out_key, out_key_size, &olen);
  xSemaphoreGive(lock);

  if (status != PSA_SUCCESS) {
    ESP_LOGE(TAG, "RSA AES key decrypt failed: %d", (int)status);
    return -1;
  }

  *out_key_len = olen;
  ESP_LOGI(TAG, "Decrypted AES key: %zu bytes", olen);
  return 0;
}
